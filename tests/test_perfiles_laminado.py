"""Importar una calibración hecha en eufyMake Studio a un perfil plano de
PrusaSlicer (F1.12 (laminado)).

El usuario calibró la M5 en eufyMake Studio, que es un PrusaSlicer
modificado: su paquete de configuración trae varios perfiles de impresión,
de filamento y de impresora, y claves que PrusaSlicer no entiende. Lo
esperado sale del texto literal del paquete de prueba, no del importador.
"""

import pytest

from orchestrator.perfiles_laminado import (
    PaqueteInseguro, PresetDesconocido, aplanar, claves_conocidas, escribir_ini,
    guardar_origen, leer_paquete)

PAQUETE = """\
# generated by eufyMake Studio 3D

[print:Fast]
layer_height = 0.25
perimeters = 4
jerk_e_print = 3

[print:Precision]
inherits = Normal - M5 0.4mm - PLA+ Basic
layer_height = 0.12
perimeters = 3
fill_density = 20%
jerk_e_print = 5
first_layer_flow_ratio = 1.2
hole_offset = 0.05
print_temperature = nil

[filament:AnkerMake PLA+]
temperature = 215
filament_density = 1.24

[filament:esun pla+]
inherits = AnkerMake PLA+ Basic (White)
temperature = 210
first_layer_bed_temperature = 60
filament_density = 1.24
anker_colour_id = 10010002

[printer:AnkerMake M5 0.4 mm Nozzle - Copy]
bed_shape = 0x0,235x0,235x235,0x235
z_offset = -0.05
host_type = ankerlink
print_host =
printhost_apikey =
start_gcode = M104 S{first_layer_temperature[0]}\\nG28 ;Home

[presets]
print = Precision
filament = esun pla+
printer = AnkerMake M5 0.4 mm Nozzle - Copy
"""

TRIO = dict(impresion="Precision", filamento="esun pla+",
            impresora="AnkerMake M5 0.4 mm Nozzle - Copy")


@pytest.fixture
def paquete(tmp_path):
    ruta = tmp_path / "bundle.ini"
    ruta.write_text(PAQUETE, encoding="utf-8")
    return leer_paquete(ruta)


def test_cada_valor_sale_del_preset_elegido_y_no_de_sus_hermanos(paquete):
    """Hay dos filamentos con temperaturas distintas y dos perfiles de
    impresión con capas distintas: mezclarlos imprimiría a 215 °C lo que se
    calibró a 210."""
    plano, _ = aplanar(paquete, **TRIO)

    assert plano["temperature"] == "210"
    assert plano["first_layer_bed_temperature"] == "60"
    assert plano["layer_height"] == "0.12"
    assert plano["perimeters"] == "3"
    assert plano["z_offset"] == "-0.05"
    # Los saltos de línea del G-code se quedan escritos como \\n, igual que
    # en el paquete: PrusaSlicer los lee así.
    assert plano["start_gcode"] == "M104 S{first_layer_temperature[0]}\\nG28 ;Home"


def test_lo_que_prusaslicer_no_entiende_se_quita_y_se_dice(paquete):
    plano, descartadas = aplanar(paquete, **TRIO)

    for clave in ("jerk_e_print", "first_layer_flow_ratio", "hole_offset", "anker_colour_id"):
        assert clave not in plano
        assert clave in descartadas
    # Con su valor: «first_layer_flow_ratio = 1.2» es lo que hay que saber
    # para entender por qué la primera capa sale distinta que en eufyMake.
    assert descartadas["first_layer_flow_ratio"] == "1.2"


def test_lo_que_no_tiene_valor_no_se_anota_como_perdido(paquete):
    """`print_temperature = nil` no fija nada en eufyMake: anotarlo como
    perdido haría creer que se pierde una temperatura."""
    _, descartadas = aplanar(paquete, **TRIO)
    assert "print_temperature" not in descartadas


def test_la_conexion_con_la_impresora_no_viaja_en_el_perfil(paquete):
    """`host_type = ankerlink` ni siquiera es válido en PrusaSlicer (lo
    cambia por prusalink al cargar), y la dirección y la clave del host son
    de la máquina de cada uno, no de cómo se lamina."""
    plano, _ = aplanar(paquete, **TRIO)
    for clave in ("host_type", "print_host", "printhost_apikey"):
        assert clave not in plano


def test_inherits_no_pasa_al_perfil_plano(paquete):
    """En un perfil plano no hay de quién heredar: con `inherits`,
    PrusaSlicer buscaría un preset del sistema que este PC no tiene."""
    plano, _ = aplanar(paquete, **TRIO)
    assert "inherits" not in plano


def test_un_preset_que_no_esta_en_el_paquete_se_dice_con_los_que_hay(paquete):
    with pytest.raises(PresetDesconocido, match="esun pla\\+"):
        aplanar(paquete, impresion="Precision", filamento="eSun PETG",
                impresora=TRIO["impresora"])


def test_el_ini_escrito_dice_de_donde_viene_y_que_se_perdio(paquete, tmp_path):
    plano, descartadas = aplanar(paquete, **TRIO)
    destino = tmp_path / "m5.ini"

    escribir_ini(plano, destino, origen="bundle.ini", trio=TRIO, descartadas=descartadas)

    texto = destino.read_text(encoding="utf-8")
    cabecera = [l for l in texto.splitlines() if l.startswith("#")]
    cuerpo = [l for l in texto.splitlines() if l and not l.startswith("#")]
    assert any("bundle.ini" in l for l in cabecera)
    assert any("esun pla+" in l for l in cabecera)
    assert any("first_layer_flow_ratio = 1.2" in l for l in cabecera)
    assert any("SIN VERIFICAR" in l for l in cabecera)
    assert "temperature = 210" in cuerpo
    assert cuerpo == sorted(cuerpo)


def test_la_lista_de_claves_es_la_de_prusaslicer():
    """Sale de lo que PrusaSlicer 2.9.6 guardó al cargar el paquete real.
    Sin ella, el importador no sabría qué quitar."""
    conocidas = claves_conocidas()
    assert {"temperature", "layer_height", "start_gcode", "z_offset"} <= conocidas
    assert "jerk_e_print" not in conocidas


def test_un_paquete_con_la_clave_de_la_impresora_no_se_guarda(tmp_path):
    """El paquete original se guarda en el repositorio para poder
    regenerar el perfil. Si trae la clave del host de la impresora, eso
    sería publicarla."""
    ruta = tmp_path / "bundle.ini"
    ruta.write_text(PAQUETE.replace("printhost_apikey =", "printhost_apikey = abc123"),
                    encoding="utf-8")

    with pytest.raises(PaqueteInseguro, match="printhost_apikey"):
        guardar_origen(ruta, tmp_path / "origen")
    assert not (tmp_path / "origen").exists()


def test_un_paquete_sin_secretos_se_guarda_tal_cual(tmp_path):
    ruta = tmp_path / "bundle.ini"
    ruta.write_text(PAQUETE, encoding="utf-8")

    copia = guardar_origen(ruta, tmp_path / "origen")

    assert copia.read_text(encoding="utf-8") == PAQUETE


# --- Con PrusaSlicer de verdad (en el host) ----------------------------------


def _prusaslicer():
    from orchestrator.slicing import prusaslicer
    return prusaslicer()


@pytest.mark.skipif(_prusaslicer() is None, reason="PrusaSlicer no disponible")
def test_prusaslicer_carga_el_perfil_importado_sin_cambiar_ni_tirar_nada(tmp_path):
    """El oráculo es PrusaSlicer: si al guardar lo que cargó falta una
    clave o cambia un valor, el perfil no dice lo que creemos."""
    import subprocess
    from pathlib import Path

    perfil = Path("config/slicing/m5_esun_plamas_precision.ini")
    salida = tmp_path / "guardado.ini"
    r = subprocess.run([_prusaslicer(), "--load", str(perfil), "--save", str(salida)],
                       capture_output=True, text=True, timeout=120)

    assert r.returncode == 0, r.stderr
    assert "substituted" not in r.stdout + r.stderr
    leidas = lambda p: {l.split(" = ", 1)[0] for l in p.read_text(encoding="utf-8").splitlines()  # noqa: E731
                        if " = " in l and not l.startswith("#")}
    assert leidas(perfil) <= leidas(salida)


@pytest.mark.skipif(_prusaslicer() is None, reason="PrusaSlicer no disponible")
def test_el_gcode_sale_con_la_calibracion_del_usuario(tmp_path):
    """Los valores esperados son los del paquete de eufyMake, filamento
    «esun pla+» y perfil «Precision», leídos a mano."""
    from pathlib import Path

    from orchestrator.slicing import slice_stl
    from tests.test_slicing import _cubo_stl

    stl = tmp_path / "cubo.stl"
    _cubo_stl(stl)
    informe = slice_stl(stl, Path("config/slicing/m5_esun_plamas_precision.ini"),
                        tmp_path / "cubo.gcode")

    gcode = (tmp_path / "cubo.gcode").read_text(errors="ignore")
    for linea in ("; temperature = 210", "; first_layer_temperature = 215",
                  "; first_layer_bed_temperature = 60", "; layer_height = 0.12",
                  "; filament_retract_length = 1", "; z_offset = -0.05"):
        assert linea in gcode, linea
    # 20 mm de PLA macizo serían 8 cm³ × 1.24 g/cm³.
    assert 0 < informe.grams < 8 * 1.24
